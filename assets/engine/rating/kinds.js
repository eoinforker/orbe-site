/*
  The five kinds Orbe rates, as data.

  Every prior median and sigma here is PROVISIONAL: a stated guess, not a
  measurement. The YouTube ones carry over from the public engine on the site;
  the rest are first guesses of the same shape. Each is replaced by a measured
  distribution through fitPriors() once enough creators of that kind and size
  have consented to be counted, and the published maths says which is which.
*/
const percentOf = (suffix) => ({ as: "percent", suffix });
// Shared parts, so the meaning of momentum, hit rate and cadence is the same everywhere.
const momentum = (metric, weight, sigma, worksNoun) => ({
    key: "momentum",
    name: "Momentum",
    weight,
    measure: { type: "momentum", metric, recent: 10, before: 20 },
    scale: "log",
    prior: { median: 1, sigma },
    display: { as: "change" },
    what: `Your newest ten ${worksNoun} against the twenty before them.`,
    advice: `Recent ${worksNoun} are landing below your own norm. Look at what changed: length, topic, day or format.`,
});
const hits = (metric, weight, worksNoun, advice) => ({
    key: "hits",
    name: "Hit rate",
    weight,
    measure: { type: "hits", metric, multiple: 2 },
    scale: "linear",
    prior: { median: 0.12, sigma: 0.08 },
    display: { as: "percent" },
    what: `${worksNoun[0].toUpperCase()}${worksNoun.slice(1)} that did twice your own median or better.`,
    advice,
});
const cadence = (weight, perMonth, windowDays, worksNoun, formats) => ({
    key: "cadence",
    name: "Cadence",
    weight,
    measure: { type: "cadence", windowDays, irregularityPenalty: 0.32, irregularityAllowance: 0.8 },
    scale: "log",
    prior: { median: perMonth, sigma: 0.8, ...(formats ? { formats } : {}) },
    display: { as: "perMonth" },
    what: `How often and how steadily you publish ${worksNoun}.`,
    advice: "Long gaps cost momentum. A steady schedule you can keep beats bursts.",
});
